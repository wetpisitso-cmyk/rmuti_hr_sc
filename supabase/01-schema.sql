-- Run once in the SQL Editor of a separate, empty Supabase project.
begin;
create schema hr_internal;
revoke all on schema hr_internal from public;
grant usage on schema hr_internal to authenticated;

create table public.hr_members (
  id uuid primary key references auth.users on delete cascade,
  role text not null check(role in ('staff','hr'))
);
alter table public.hr_members enable row level security;
create policy own_membership on public.hr_members for select to authenticated using (id=(select auth.uid()));
create function hr_internal.is_member() returns boolean language sql stable security invoker set search_path='' as $$
 select exists(select 1 from public.hr_members where id=(select auth.uid()));
$$;
create function hr_internal.is_hr() returns boolean language sql stable security invoker set search_path='' as $$
 select exists(select 1 from public.hr_members where id=(select auth.uid()) and role='hr');
$$;

create table public.hr_orgs (
  id integer generated by default as identity primary key,
  campus text not null, faculty text not null, division text not null, unit text not null,
  unique(campus,faculty,division,unit)
);
create table public.hr_profiles (
  id uuid primary key references public.hr_members on delete cascade,
  prefix text not null, first_name text not null, last_name text not null,
  staff_type text, position text, track text, org_id integer references public.hr_orgs, verified_at timestamptz
);
create table public.hr_signatures (
  owner_id uuid primary key references public.hr_members on delete cascade,
  strokes jsonb not null check(jsonb_typeof(strokes)='array' and jsonb_array_length(strokes) between 1 and 150 and octet_length(strokes::text)<=160000)
);
create table public.hr_assets (
  id uuid primary key default gen_random_uuid(), owner_id uuid not null references public.hr_members,
  code text not null unique, title text not null, location text not null, issued_on date not null
);
create table public.hr_feedback (
  id uuid primary key default gen_random_uuid(), owner_id uuid not null default auth.uid() references public.hr_members,
  score int not null check(score between 1 and 5), comment text not null default '' check(length(comment)<=1000),
  created_at timestamptz not null default now()
);
create table public.hr_requests (
  id uuid primary key default gen_random_uuid(), number bigint generated always as identity unique,
  owner_id uuid not null default auth.uid() references public.hr_members,
  kind text not null check(kind in ('salary','contract')), purpose text not null check(length(trim(purpose)) between 1 and 600),
  copies int not null check(copies between 1 and 5), status text not null default 'submitted'
    check(status in ('submitted','review','ready','done','rejected')),
  note text not null default '' check(length(note)<=600), document_path text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create function hr_internal.check_transition() returns trigger language plpgsql set search_path='' as $$
begin
  if not ((old.status='submitted' and new.status in ('review','rejected')) or
          (old.status='review' and new.status in ('ready','rejected')) or
          (old.status='ready' and new.status='done')) then
    raise exception 'สถานะคำขอเปลี่ยนไปแล้ว กรุณาโหลดใหม่';
  end if;
  if new.status in ('ready','rejected') and trim(new.note)='' then raise exception 'กรุณาระบุสถานที่รับเอกสารหรือเหตุผลที่ส่งคืน'; end if;
  if new.document_path is distinct from old.document_path and
     (new.status<>'ready' or new.document_path is null or new.document_path !~ '^drive:[A-Za-z0-9_-]{10,200}$') then
    raise exception 'ตำแหน่งไฟล์เอกสารไม่ถูกต้อง';
  end if;
  new.updated_at=now();
  return new;
end;
$$;
create trigger request_transition before update on public.hr_requests for each row execute function hr_internal.check_transition();
create table public.hr_orders (
  id uuid primary key default gen_random_uuid(), number text not null unique check(length(trim(number)) between 1 and 80),
  title text not null check(length(trim(title)) between 1 and 200), issued_on date not null,
  recipient_id uuid references public.hr_members, body text not null check(length(trim(body)) between 1 and 6000)
);
create table public.hr_activities (
  id uuid primary key default gen_random_uuid(), title text not null check(length(trim(title)) between 1 and 200),
  venue text not null check(length(trim(venue)) between 1 and 250), starts_at timestamptz not null,
  capacity integer not null check(capacity between 1 and 10000), taken integer not null default 0 check(taken between 0 and capacity)
);
create table public.hr_registrations (
  id uuid primary key default gen_random_uuid(), owner_id uuid not null default auth.uid() references public.hr_members,
  activity_id uuid not null references public.hr_activities, created_at timestamptz not null default now(), unique(activity_id,owner_id)
);
-- Reserve/release one place atomically. The client has no UPDATE permission on taken.
create function hr_internal.count_places() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if (select auth.uid()) is null then raise exception 'กรุณาเข้าสู่ระบบ'; end if;
 if tg_op='INSERT' then
   if new.owner_id<>(select auth.uid()) then raise exception 'ผู้ลงทะเบียนไม่ตรงกับบัญชี'; end if;
   update public.hr_activities set taken=taken+1 where id=new.activity_id and taken<capacity and starts_at>now();
   if not found then raise exception 'กิจกรรมเต็มหรือปิดรับแล้ว'; end if;
 else
   if old.owner_id<>(select auth.uid()) then raise exception 'บัญชีไม่ตรงกับผู้ลงทะเบียน'; end if;
   update public.hr_activities set taken=taken-1 where id=old.activity_id and starts_at>now();
   if not found then raise exception 'กิจกรรมเริ่มแล้ว'; end if;
 end if;
 return null;
end;
$$;
create trigger count_registrations after insert or delete on public.hr_registrations for each row execute function hr_internal.count_places();

create table public.hr_assessments (
 id uuid primary key default gen_random_uuid(), owner_id uuid not null default auth.uid() references public.hr_members,
 period text not null check(period ~ '^[0-9]{4}/[12]$'), summary text not null check(length(trim(summary)) between 1 and 3000),
 created_at timestamptz not null default now(), unique(owner_id,period)
);
create index hr_requests_owner on public.hr_requests(owner_id,created_at desc);
create index hr_assets_owner on public.hr_assets(owner_id);
create index hr_orders_recipient on public.hr_orders(recipient_id);
create index hr_registrations_owner on public.hr_registrations(owner_id);
create index hr_feedback_owner on public.hr_feedback(owner_id);
do $$
declare t text;
begin
 foreach t in array array['members','orgs','profiles','signatures','assets','feedback','requests','orders','activities','registrations','assessments'] loop
   execute format('alter table public.%I enable row level security','hr_'||t);
   execute format('revoke all on public.%I from PUBLIC, anon, authenticated','hr_'||t);
   execute format('grant select on public.%I to authenticated','hr_'||t);
 end loop;
end $$;
revoke all on all functions in schema hr_internal from public, anon, authenticated;
grant execute on function hr_internal.is_member(),hr_internal.is_hr() to authenticated;

create policy member_org on public.hr_orgs for select to authenticated using ((select hr_internal.is_member()));
create policy read_profiles on public.hr_profiles for select to authenticated using (id=(select auth.uid()) or (select hr_internal.is_hr()));
create policy edit_own_profile on public.hr_profiles for update to authenticated using (id=(select auth.uid())) with check (id=(select auth.uid()));
grant update(staff_type,position,track,org_id) on public.hr_profiles to authenticated;
create policy own_signature on public.hr_signatures for all to authenticated using(owner_id=(select auth.uid())) with check(owner_id=(select auth.uid()));
grant insert(owner_id,strokes),update(strokes,owner_id),delete on public.hr_signatures to authenticated;
create policy read_assets on public.hr_assets for select to authenticated using(owner_id=(select auth.uid()) or (select hr_internal.is_hr()));
create policy give_asset on public.hr_assets for insert to authenticated with check ((select hr_internal.is_hr()));
grant insert(owner_id,code,title,location,issued_on) on public.hr_assets to authenticated;
create policy read_feedback on public.hr_feedback for select to authenticated using(owner_id=(select auth.uid()) or (select hr_internal.is_hr()));
create policy send_feedback on public.hr_feedback for insert to authenticated with check(owner_id=(select auth.uid()));
grant insert(score,comment) on public.hr_feedback to authenticated;
create policy read_requests on public.hr_requests for select to authenticated using(owner_id=(select auth.uid()) or (select hr_internal.is_hr()));
create policy request_doc on public.hr_requests for insert to authenticated with check (owner_id=(select auth.uid()) and status='submitted');
grant insert(id,kind,purpose,copies) on public.hr_requests to authenticated;
create policy process_request on public.hr_requests for update to authenticated using ((select hr_internal.is_hr())) with check ((select hr_internal.is_hr()));
grant update(status,note,document_path) on public.hr_requests to authenticated;
create policy read_orders on public.hr_orders for select to authenticated using ((select hr_internal.is_member()) and (recipient_id is null or recipient_id=(select auth.uid()) or (select hr_internal.is_hr())));
create policy publish_order on public.hr_orders for insert to authenticated with check ((select hr_internal.is_hr()));
grant insert(number,title,issued_on,recipient_id,body) on public.hr_orders to authenticated;
create policy read_activities on public.hr_activities for select to authenticated using ((select hr_internal.is_member()));
create policy publish_activity on public.hr_activities for insert to authenticated with check ((select hr_internal.is_hr()));
grant insert(title,venue,starts_at,capacity) on public.hr_activities to authenticated;
create policy read_registration on public.hr_registrations for select to authenticated using(owner_id=(select auth.uid()) or (select hr_internal.is_hr()));
create policy join_activity on public.hr_registrations for insert to authenticated with check(owner_id=(select auth.uid()));
grant insert(activity_id),delete on public.hr_registrations to authenticated;
create policy cancel_registration on public.hr_registrations for delete to authenticated using(owner_id=(select auth.uid()));
create policy read_assessment on public.hr_assessments for select to authenticated using(owner_id=(select auth.uid()) or (select hr_internal.is_hr()));
create policy submit_assessment on public.hr_assessments for insert to authenticated with check(owner_id=(select auth.uid()));
grant insert(period,summary) on public.hr_assessments to authenticated;
commit;
